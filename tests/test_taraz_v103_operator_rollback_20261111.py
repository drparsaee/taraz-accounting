"""Taraz v103->v102 rollback: real pinned EXE copies, simulated private install.

The scripts never run an EXE or touch the real installed pointer. Set
TARAZ_V103_ROLLBACK_GATE to a new gate directory generated by the worker's
operator rollback generator, then run unittest on Windows.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts import taraz_v103_operator_rollback_20261111 as gate


@unittest.skipUnless(os.name == "nt" and shutil.which("powershell.exe"),
                     "Native Windows PowerShell is required")
class RollbackContractTests(unittest.TestCase):
    def test_pinned_frozen_release_metadata(self):
        metadata = gate.frozen_candidate_preflight()
        self.assertEqual(metadata["candidateExeSha256"], gate.FROZEN_EXE_SHA)
        self.assertEqual(metadata["previousInstalledExeSha256"], gate.OLD_EXE_SHA)
        self.assertEqual(metadata["candidateSourceSha256"], gate.FROZEN_SOURCE_SHA)

    def test_template_refuses_non_operator_mutation(self):
        source = gate.powershell_script()
        self.assertIn("if(-not $Apply)", source)
        self.assertIn("[IO.File]::Replace($pending,$pointer,$rollbackBackup,$true)", source)
        self.assertIn("RequireAbsent $rollbackBackup", source)
        self.assertIn("RequireAbsent $pending", source)
        self.assertIn("CheckNoTaraz", source)
        self.assertIn("CheckWriteRights", source)
        self.assertIn("current-version-pre-1.0.3.txt", source)
        self.assertIn("current-version-pre-rollback-1.0.3.txt", source)
        self.assertIn(gate.OLD_EXE_SHA, source)
        self.assertIn(gate.FROZEN_EXE_SHA, source)

    def test_generator_output_manifest(self):
        folder = os.environ.get("TARAZ_V103_ROLLBACK_GATE", "")
        if not folder:
            self.skipTest("Set TARAZ_V103_ROLLBACK_GATE to the created rollback-gate-<id> directory")
        root = Path(folder)
        self.assertEqual(root.parent.resolve(), gate.OUTPUT_ROOT.resolve())
        self.assertTrue(root.name.startswith("rollback-gate-"))
        manifest = root / "rollback-gate-manifest.json"
        script = root / gate.SCRIPT_NAME
        report = json.loads(manifest.read_text(encoding="utf-8"))
        self.assertEqual(report["scriptSha256"], gate.sha(script))
        self.assertEqual(report["fromVersion"], "1.0.3")
        self.assertEqual(report["toVersion"], "1.0.2")
        self.assertFalse(report["rollbackExecuted"])
        self.assertFalse(report["installedPointerTouched"])
        self.assertTrue(report["requiresApply"])


@unittest.skipUnless(os.name == "nt" and shutil.which("powershell.exe")
                     and os.environ.get("TARAZ_V103_ROLLBACK_GATE"),
                     "Needs Windows and an explicit generated rollback gate")
class RealByteDisposableRollbackTests(unittest.TestCase):
    """Copies real pinned 1.0.2 and 1.0.3 bytes into isolated fixture roots."""

    @classmethod
    def setUpClass(cls):
        cls.gate_root = Path(os.environ["TARAZ_V103_ROLLBACK_GATE"])
        if cls.gate_root.parent.resolve() != gate.OUTPUT_ROOT.resolve():
            raise AssertionError("Fixture output must remain inside rollback gate workspace")
        cls.script = cls.gate_root / gate.SCRIPT_NAME
        cls.old_source = (Path(os.environ["LOCALAPPDATA"]) / "Programs" /
                          "Taraz" / "versions" / "1.0.2" / "Taraz.exe")
        if gate.sha(cls.old_source) != gate.OLD_EXE_SHA:
            raise AssertionError("Pinned real v1.0.2 EXE is not available for disposable tests")
        if gate.sha(gate.FROZEN_EXE) != gate.FROZEN_EXE_SHA:
            raise AssertionError("Pinned real v1.0.3 EXE has changed")
        if gate.sha(cls.script) != json.loads(
                (cls.gate_root / "rollback-gate-manifest.json").read_text())["scriptSha256"]:
            raise AssertionError("Generated rollback PS1 SHA has changed")

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="simulated-installed-",
                                                dir=self.gate_root)
        self.addCleanup(self.tmp.cleanup)
        self.fixture = Path(self.tmp.name)
        if os.environ.get("TARAZ_V103_ROLLBACK_TEST_DRAFT") == "1":
            # Iteration-only test script; final acceptance runs immutable
            # generated PS1 and validates its manifest SHA separately.
            self.script = self.fixture / gate.SCRIPT_NAME
            self.script.write_text(gate.powershell_script(), encoding="utf-8")
        self.local = self.fixture / "isolated-localappdata"
        self.roaming = self.fixture / "isolated-appdata"
        self.installed = self.local / "Programs" / "Taraz"
        v102 = self.installed / "versions" / "1.0.2"
        v103 = self.installed / "versions" / "1.0.3"
        v102.mkdir(parents=True)
        v103.mkdir(parents=True)
        self.old = v102 / "Taraz.exe"
        self.new = v103 / "Taraz.exe"
        shutil.copyfile(self.old_source, self.old)
        shutil.copyfile(gate.FROZEN_EXE, self.new)
        self.pointer = self.installed / "current-version.txt"
        self.pointer.write_bytes(b"1.0.3\r\n")
        self.old_pointer = self.installed / "current-version-pre-1.0.3.txt"
        self.old_pointer.write_bytes(b"1.0.2\r\n")
        self.launcher = self.installed / "Run-Taraz.cmd"
        self.launcher.write_text(
            '@echo off\nstart "" "%~dp0versions\\%TARAZ_VERSION%\\Taraz.exe"\n',
            encoding="utf-8")
        self.roaming.mkdir()
        self.ledger = self.roaming / "Taraz" / "finance-sentinel.db"
        self.ledger.parent.mkdir()
        self.ledger.write_bytes(b"TEST-ONLY-DATA-SENTINEL-NOT-REAL-FINANCE")
        self.canary_sha = gate.sha(self.ledger)

    def tearDown(self):
        self.assertEqual(gate.sha(self.ledger), self.canary_sha,
                         "Rollback must never modify a financial data root")
        self.assertEqual(gate.sha(self.old), gate.OLD_EXE_SHA,
                         "Rollback must retain byte-exact v1.0.2 executable")
        self.assertEqual(gate.sha(self.new), gate.FROZEN_EXE_SHA,
                         "Rollback must retain byte-exact v1.0.3 executable")

    def invoke(self, *args: str, wrapper: str = "") -> subprocess.CompletedProcess[str]:
        env = dict(os.environ)
        env["LOCALAPPDATA"] = str(self.local)
        env["APPDATA"] = str(self.roaming)
        # The host may be running unrelated Taraz QA processes on another
        # desktop. Keep synthetic install tests deterministic by injecting a
        # PowerShell CIM function in the disposable wrapper, without editing
        # the immutable operator script. Explicit negative tests replace it.
        cim = wrapper or "function Get-CimInstance { @() }"
        helper = self.fixture / "invoke-with-test-command.ps1"
        helper.write_text(cim + "\n& '" + str(self.script).replace("'", "''") +
                          "' " + " ".join(args) + "\n", encoding="utf-8")
        return subprocess.run([shutil.which("powershell.exe"), "-NoProfile", "-NonInteractive",
                               "-ExecutionPolicy", "Bypass", "-File", str(helper)],
                              env=env, capture_output=True, text=True,
                              encoding="utf-8", errors="replace", check=False, timeout=35)

    def blocked(self, expected: str, *args: str, wrapper: str = ""):
        before = self.pointer.read_bytes() if self.pointer.exists() else None
        result = self.invoke(*args, wrapper=wrapper)
        self.assertNotEqual(result.returncode, 0, (result.stdout, result.stderr))
        self.assertIn(expected.casefold(), (result.stdout + result.stderr).casefold())
        if before is not None:
            self.assertEqual(self.pointer.read_bytes(), before)
        self.assertFalse((self.installed / "current-version-pre-rollback-1.0.3.txt").exists())
        return result

    def test_preflight_only_does_not_mutate_any_file(self):
        def snapshot():
            return {str(p.relative_to(self.fixture)): gate.sha(p)
                    for root in (self.installed, self.roaming)
                    for p in root.rglob("*") if p.is_file()}
        before = snapshot()
        result = self.invoke()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("READY_FOR_OPERATOR_ROLLBACK_1.0.3_TO_1.0.2_NO_CHANGES", result.stdout)
        self.assertEqual(before, snapshot())

    def test_apply_changes_pointer_only_and_creates_dedicated_backup(self):
        result = self.invoke("-Apply")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("ROLLED_BACK_POINTER_TO_1.0.2_BOTH_BINARIES_RETAINED", result.stdout)
        self.assertEqual(self.pointer.read_bytes(), b"1.0.2\r\n")
        self.assertEqual((self.installed / "current-version-pre-rollback-1.0.3.txt").read_bytes(),
                         b"1.0.3\r\n")
        self.assertEqual(self.old_pointer.read_bytes(), b"1.0.2\r\n")
        self.assertFalse((self.installed / "current-version-rollback-to-1.0.2-pending.txt").exists())
        again = self.invoke("-Apply")
        self.assertNotEqual(again.returncode, 0)
        self.assertEqual(self.pointer.read_bytes(), b"1.0.2\r\n")

    def test_modified_pointer_blocks(self):
        self.pointer.write_bytes(b"1.0.2\r\n")
        self.blocked("pointer", "-Apply")

    def test_tampered_v102_exe_hash_blocks(self):
        with self.old.open("ab") as file:
            file.write(b"TAMPER")
        try:
            self.blocked("original v1.0.2 binary hash", "-Apply")
        finally:
            shutil.copyfile(self.old_source, self.old)

    def test_tampered_v103_exe_hash_blocks(self):
        with self.new.open("ab") as file:
            file.write(b"TAMPER")
        try:
            self.blocked("current v1.0.3 binary hash", "-Apply")
        finally:
            shutil.copyfile(gate.FROZEN_EXE, self.new)

    def test_missing_pre_activation_backup_blocks(self):
        self.old_pointer.unlink()
        self.blocked("required path", "-Apply")

    def test_corrupt_original_pointer_backup_blocks(self):
        self.old_pointer.write_bytes(b"1.0.1\r\n")
        self.blocked("original 1.0.2 pointer backup", "-Apply")

    def test_rejects_existing_rollback_backup(self):
        (self.installed / "current-version-pre-rollback-1.0.3.txt").write_text("already exists")
        before = self.pointer.read_bytes()
        result = self.invoke("-Apply")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("never overwrite", result.stderr.lower())
        self.assertEqual(self.pointer.read_bytes(), before)

    def test_rejects_existing_pending_pointer(self):
        (self.installed / "current-version-rollback-to-1.0.2-pending.txt").write_text("already exists")
        self.blocked("never overwrite", "-Apply")

    def test_rejects_invalid_launcher(self):
        self.launcher.write_text("@echo off\nstart Taraz.exe\n")
        self.blocked("launcher contract", "-Apply")

    def test_rejects_readonly_pointer_permission(self):
        self.pointer.chmod(stat.S_IREAD)
        try:
            self.blocked("read-only", "-Apply")
        finally:
            self.pointer.chmod(stat.S_IWRITE)

    def test_process_already_running_blocks(self):
        helper = "function Get-CimInstance { [pscustomobject]@{Name='Taraz.exe'} }"
        self.blocked("process is running", "-Apply", wrapper=helper)

    def test_process_query_failure_blocks(self):
        helper = "function Get-CimInstance { throw 'Synthetic CIM outage' }"
        self.blocked("process inactivity", "-Apply", wrapper=helper)

    def test_unsafe_symlink_pointer_blocks(self):
        backup = self.fixture / "test-pointer-copy.txt"
        backup.write_bytes(self.pointer.read_bytes())
        self.pointer.unlink()
        try:
            self.pointer.symlink_to(backup)
        except (OSError, NotImplementedError):
            self.skipTest("Windows does not grant symlink creation")
        self.blocked("linked/junction", "-Apply")

    def test_hardlinked_pointer_is_rejected(self):
        anchor = self.fixture / "hardlink-pointer-anchor.txt"
        os.link(self.pointer, anchor)
        self.blocked("Hardlink", "-Apply")

    def test_hardlinked_old_executable_is_rejected(self):
        anchor = self.fixture / "hardlink-old-exe-anchor.bin"
        os.link(self.old, anchor)
        self.blocked("Hardlink", "-Apply")

    def test_hardlinked_new_executable_is_rejected(self):
        anchor = self.fixture / "hardlink-new-exe-anchor.bin"
        os.link(self.new, anchor)
        self.blocked("Hardlink", "-Apply")

    def test_missing_previous_executable_blocks(self):
        self.old.rename(self.fixture / "previous-exe-temp")
        try:
            self.blocked("required path", "-Apply")
        finally:
            (self.fixture / "previous-exe-temp").rename(self.old)

    def test_wrong_pe_version_blocks_even_with_digest_pins(self):
        # No EXE modification needed: temporarily relabel a copy so exact
        # SHA still passes only for the correct version and wrong PE fails.
        # This deliberately tests the independent PE checker using 1.0.3.
        target = self.fixture / "wrong-version.ps1"
        code = gate.powershell_script()
        code = code.replace("CheckVersion $new 3", "CheckVersion $new 2")
        target.write_text(code, encoding="utf-8")
        before = self.pointer.read_bytes()
        env = dict(os.environ, LOCALAPPDATA=str(self.local), APPDATA=str(self.roaming))
        wrapper = self.fixture / "invoke-wrong-pe.ps1"
        wrapper.write_text("function Get-CimInstance { @() }\n& '" +
                           str(target).replace("'", "''") + "' -Apply\n", encoding="utf-8")
        result = subprocess.run([shutil.which("powershell.exe"), "-NoProfile", "-NonInteractive",
                                 "-ExecutionPolicy", "Bypass", "-File", str(wrapper)],
                                env=env, capture_output=True, text=True,
                                encoding="utf-8", errors="replace", timeout=35)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("PE version", result.stderr)
        self.assertEqual(self.pointer.read_bytes(), before)


if __name__ == "__main__":
    unittest.main()
